import { expect, test } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';

test('one live session carries accept, override, refusal and decline across the console', async ({ page }) => {
  test.setTimeout(90_000);
  const shots = path.resolve('../docs/course/LX40_shots');
  const capture = process.env.SENTINEL_CAPTURE_LX40 === '1';
  if (capture) await mkdir(shots, { recursive: true });
  const shot = async (name: string) => { if (capture) await page.screenshot({ path: path.join(shots, `${name}.png`), fullPage: true, animations: 'disabled' }); };
  await page.setViewportSize({ width: 1280, height: 720 });
  await page.goto('/live');
  await expect(page.getByRole('heading', { name: 'Live Operations' })).toBeVisible();
  await page.getByLabel('Seed').fill('620004');
  await page.getByRole('button', { name: 'Start' }).click();
  const bar = page.getByRole('region', { name: 'Operator decides' });
  await expect(bar.getByRole('button', { name: 'Accept' })).toBeVisible();
  await expect(bar.getByRole('button', { name: 'Override' })).toBeVisible();
  await expect(bar.getByRole('button', { name: 'Decline' })).toBeVisible();
  const liveNav = page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: 'Live Operations' });
  await expect(liveNav.locator('span')).toHaveText('1');
  await shot('01-pending');
  await page.getByRole('tab', { name: 'Decisions log' }).click();
  await bar.getByRole('button', { name: 'Accept' }).click();
  await expect(page.getByRole('region', { name: 'Decisions log' })).toContainText('ACCEPT');
  await expect(page.getByRole('group', { name: 'Action route marks' })).toContainText('accept');
  await expect(page.getByRole('status').filter({ hasText: 'Accept recorded' })).toBeVisible();
  await expect(liveNav.locator('span')).toHaveCount(0);
  await shot('02-accept');
  await bar.getByRole('button', { name: 'STEP ON' }).click();
  await expect(bar.getByRole('button', { name: 'Override' })).toBeVisible();
  await bar.getByRole('button', { name: 'Override' }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog.getByRole('button', { name: 'Confirm override' })).toBeDisabled();
  await dialog.getByRole('radio', { name: 'Road report' }).check();
  await dialog.getByLabel('REASON').fill('Bridge flooded');
  await shot('03-override-preview');
  await dialog.getByRole('button', { name: 'Confirm override' }).click();
  await expect(dialog).toContainText('CERT-000002');
  await expect(page.getByRole('region', { name: 'Decisions log' })).toContainText('OVERRIDE');
  await expect(page.getByRole('group', { name: 'Action route marks' })).toContainText('override');
  await shot('04-override');
  await dialog.getByRole('button', { name: 'Step on' }).click();
  await bar.getByRole('button', { name: 'Override' }).click();
  await dialog.getByRole('combobox', { name: /Alternative/ }).selectOption('Z3->S3');
  await dialog.getByRole('radio', { name: 'Road report' }).check();
  await dialog.getByLabel('REASON').fill('Route looks unsafe');
  await dialog.getByRole('button', { name: 'Confirm override' }).click();
  await expect(dialog.getByRole('alert')).toContainText('Gate refused');
  await expect(page.getByRole('region', { name: 'Decisions log' })).toContainText('REFUSED');
  await shot('05-refused');
  await dialog.getByRole('button', { name: 'Decline' }).click();
  await dialog.getByLabel('REASON').fill('Hold pending field report');
  await dialog.getByRole('button', { name: 'Confirm decline' }).click();
  await expect(dialog).toContainText('CERT-000003');
  await expect(page.getByRole('group', { name: 'Action route marks' })).toContainText('decline');
  await shot('06-decline');
  await dialog.getByRole('button', { name: 'Minimise decision' }).click();
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: 'Overview' }).click();
  await expect(page.getByRole('heading', { name: /Live session/ })).toBeVisible();
  await expect(page.getByText('Last five decisions')).toBeVisible();
  await shot('07-overview');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: 'Decisions & Certificates' }).click();
  await page.getByLabel('Show this live session').check();
  await expect(page).toHaveURL(/session=fixture-session/);
  await expect(page.getByLabel('Decision list')).toContainText('CERT-000003');
  await shot('08-decisions');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: 'Live Operations' }).click();
  await page.getByRole('tab', { name: 'Decisions log' }).click();
  await expect(page.getByRole('region', { name: 'Decisions log' })).toContainText('OVERRIDE');
  await shot('09-return');
  await page.getByRole('tab', { name: 'Shelters' }).click();
  await shot('10-shelters');
  await page.getByRole('tab', { name: 'Zones' }).click();
  await shot('11-zones');
  await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight));
  await expect(bar.getByRole('button', { name: 'STEP ON' })).toBeInViewport();
  const axe = await new AxeBuilder({ page }).analyze();
  expect(axe.violations.filter(item => item.impact === 'serious' || item.impact === 'critical')).toEqual([]);
});

test('recorded walkthrough writes a clearly labelled practice decision', async ({ page }) => {
  await page.goto('/live');
  await page.getByRole('radio', { name: 'Guided demo' }).check();
  await page.getByRole('button', { name: 'Next step' }).click();
  await page.getByRole('button', { name: 'Next step' }).click();
  await page.getByRole('region', { name: 'Operator decides' }).getByRole('button', { name: 'Override' }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog).toBeVisible();
  await dialog.getByRole('radio', { name: 'Road report' }).check();
  await dialog.getByLabel('REASON').fill('Bridge inspection pending');
  await dialog.getByRole('button', { name: 'Confirm override' }).click();
  await expect(page.getByRole('status').filter({ hasText: 'PRACTICE — not sent to the engine' })).toBeVisible();
  await page.getByRole('button', { name: 'Decisions log' }).click();
  await expect(page.getByRole('region', { name: 'Decisions log' })).toContainText('PRACTICE');
  if (process.env.SENTINEL_CAPTURE_LX40 === '1') {
    const shots = path.resolve('../docs/course/LX40_shots');
    await mkdir(shots, { recursive: true });
    await page.screenshot({ path: path.join(shots, '12-practice.png'), fullPage: true, animations: 'disabled' });
  }
});
