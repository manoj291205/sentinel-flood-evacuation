"""Frozen synthetic scenario generator for the Gate 6 suites."""

from __future__ import annotations

import hashlib
import json
import random
from pathlib import Path
from typing import Literal

from src.safety import evaluate_actions

from .schemas import ScenarioV3
from .transition import initialize_episode

GENERATOR_VERSION = "v3-gate6-generator-v1"
EXACT_SEEDS = tuple(range(610000, 610120))
PRACTICAL_SEEDS = tuple(range(620000, 620120))
SuiteKind = Literal["exact", "practical"]


def _environment_seed(generator_seed: int, attempt: int) -> int:
    payload = f"environment-root-v1|{generator_seed}|{attempt}".encode()
    return int.from_bytes(hashlib.sha256(payload).digest()[:8], "big")


def _location(node_id: str) -> dict:
    return {
        "kind": "ABSTRACT_NODE",
        "node_id": node_id,
        "latitude": None,
        "longitude": None,
    }


def _provenance() -> dict:
    def component(classification: str, description: str) -> dict:
        return {
            "classification": classification,
            "description": description,
            "source_refs": [],
        }

    return {
        "scenario_origin": component(
            "SIMULATED", "Synthetic Gate 6 scenario generated from frozen distributions."
        ),
        "geography_origin": component(
            "FICTIONAL", "Abstract fictional nodes; no real geography or coordinates."
        ),
        "population_origin": component("SIMULATED", "Synthetic integer populations."),
        "shelter_origin": component(
            "FICTIONAL", "Synthetic shelter capacities, states, and severities."
        ),
        "hazard_origin": component(
            "SIMULATED", "Synthetic normalized initial hazards and Phase 4 dynamics."
        ),
        "travel_origin": component(
            "SIMULATED", "Synthetic travel distributions and closure probabilities."
        ),
        "network_origin": component(
            "FICTIONAL", "Complete abstract zone-shelter relation matrix."
        ),
        "notes": [
            "SIMULATED / FICTIONAL GATE 6 SCENARIO — NOT REAL DISASTER DATA.",
            f"Generated by {GENERATOR_VERSION}; no planner result enters generation.",
        ],
    }


def _raw_candidate(generator_seed: int, kind: SuiteKind, attempt: int) -> dict:
    rng = random.Random(generator_seed * 101 + attempt)
    exact = kind == "exact"
    n_zones, n_shelters, horizon = (2, 2, 5) if exact else (4, 5, 10)
    pop_range = (20, 60) if exact else (40, 120)
    capacity_range = (50, 100) if exact else (100, 260)
    travel_high = 25.0 if exact else 40.0

    zones = []
    for index in range(1, n_zones + 1):
        population = rng.randint(*pop_range)
        zones.append(
            {
                "zone_id": f"Z{index}",
                "location": _location(f"G6_{kind.upper()}_ZONE_{index}"),
                "population_total": population,
                "population_initial_remaining": population,
                "vulnerable_population": int(population * rng.uniform(0.10, 0.35)),
                "medical_priority_population": int(population * rng.uniform(0.05, 0.20)),
                "initial_flood_severity": round(rng.uniform(0.15, 0.85), 6),
                "initial_severity_trend": rng.choice(["RISING", "STEADY", "FALLING"]),
                "priority_features": [],
            }
        )

    shelters = []
    for index in range(1, n_shelters + 1):
        capacity = rng.randint(*capacity_range)
        draw = rng.random()
        status = "OPEN" if draw < 0.80 else "RESTRICTED" if draw < 0.95 else "CLOSED"
        shelters.append(
            {
                "shelter_id": f"S{index}",
                "location": _location(f"G6_{kind.upper()}_SHELTER_{index}"),
                "capacity_total": capacity,
                "occupancy_initial": int(capacity * rng.uniform(0.0, 0.35)),
                "status": status,
                "status_reason": (
                    None if status == "OPEN" else "Synthetic Gate 6 initial status."
                ),
                "initial_flood_severity": round(rng.uniform(0.05, 0.82), 6),
                "accessibility_score": round(rng.uniform(0.40, 1.00), 6),
            }
        )

    routes = []
    for zone in zones:
        for shelter in shelters:
            reachable = rng.random() < 0.85
            mean = rng.uniform(5.0, travel_high) if reachable else None
            routes.append(
                {
                    "route_id": f"R-{zone['zone_id']}-{shelter['shelter_id']}",
                    "source_zone_id": zone["zone_id"],
                    "destination_shelter_id": shelter["shelter_id"],
                    "reachable": reachable,
                    "travel_time_mean": round(mean, 6) if mean is not None else None,
                    "travel_time_std": (
                        round(mean * rng.uniform(0.05, 0.25), 6)
                        if mean is not None
                        else None
                    ),
                    "base_closure_probability": (
                        round(rng.uniform(0.01, 0.12), 6) if reachable else None
                    ),
                }
            )

    return {
        "schema_version": "3.0",
        "scenario_id": f"gate6-{kind}-{generator_seed:06d}",
        "seed": _environment_seed(generator_seed, attempt),
        "provenance": _provenance(),
        "time": {"timestep_minutes": 10.0, "horizon_steps": horizon},
        "zones": zones,
        "shelters": shelters,
        "fleet": {
            "evacuation_enabled": True,
            "vehicle_count": 3,
            "vehicle_capacity": 20,
            "dispatches_per_timestep": 1,
        },
        "network": {
            "network_id": f"{GENERATOR_VERSION}-{kind}",
            "mode": "ABSTRACT_ROUTES",
            "routes": routes,
        },
        "hazard": {
            "severity_min": 0.0,
            "severity_max": 1.0,
            "scale_description": "Synthetic normalized Gate 6 severity scale.",
            "thresholds_are_modeling_assumptions": True,
        },
        "stochastic_model": {
            "parameter_status": "DEFERRED_TO_PHASE_4",
            "regional_shock_std": None,
            "local_noise_std": None,
            "shock_persistence": None,
            "travel_noise_std": None,
            "closure_hazard_coefficient": None,
            "shelter_degradation_probability": None,
        },
        "policy_context": {
            "constraint_cache_version": None,
            "policy_schema_version": "v3-planner-spec-v1",
            "document_corpus_fingerprint": None,
        },
    }


def generate_gate6_scenario(generator_seed: int, kind: SuiteKind) -> ScenarioV3:
    for attempt in range(100):
        scenario = ScenarioV3.from_dict(_raw_candidate(generator_seed, kind, attempt))
        snapshot = evaluate_actions(scenario, initialize_episode(scenario))
        if any(
            item.final_allowed and item.action.to_dict()["action_type"] == "DISPATCH"
            for item in snapshot.evaluations
        ):
            return scenario
    raise RuntimeError(f"could not generate accepted Gate 6 scenario {generator_seed}")


def uncertainty_for_seed(seed: int, kind: SuiteKind) -> str:
    start = EXACT_SEEDS[0] if kind == "exact" else PRACTICAL_SEEDS[0]
    offset = seed - start
    return ("v3-low-v1", "v3-medium-v1", "v3-high-v1")[offset // 40]


def suite_manifest(kind: SuiteKind) -> dict:
    seeds = EXACT_SEEDS if kind == "exact" else PRACTICAL_SEEDS
    return {
        "generator_version": GENERATOR_VERSION,
        "suite_kind": kind,
        "number_of_scenarios": len(seeds),
        "generator_seeds": list(seeds),
        "replication_id": 0,
        "structure": (
            {"zones": 2, "shelters": 2, "horizon_steps": 5}
            if kind == "exact"
            else {"zones": 4, "shelters": 5, "horizon_steps": 10}
        ),
        "uncertainty_counts": {"LOW": 40, "MEDIUM": 40, "HIGH": 40},
        "entries": [
            {
                "generator_seed": seed,
                "scenario_id": f"gate6-{kind}-{seed:06d}",
                "uncertainty_config_id": uncertainty_for_seed(seed, kind),
                "replication_id": 0,
            }
            for seed in seeds
        ],
    }


def dump_suite(path: str | Path, kind: SuiteKind) -> None:
    Path(path).write_text(json.dumps(suite_manifest(kind), indent=2) + "\n", encoding="utf-8")
