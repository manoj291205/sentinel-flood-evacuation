"""Frozen procedural scenarios and semantic-ID permutations for Phase 9."""

from __future__ import annotations

import hashlib
import json
import random
from dataclasses import dataclass
from typing import Any

from src.safety import evaluate_actions
from src.sim import ScenarioV3
from src.sim.transition import initialize_episode

from .config import TRAINING_GENERATOR_VERSION, VALIDATION_GENERATOR_VERSION


UNCERTAINTY_IDS = ("v3-low-v1", "v3-medium-v1", "v3-high-v1")
ZONE_COUNTS = (4, 5, 6)
SHELTER_COUNTS = (6, 7, 8, 9)
HORIZONS = tuple(range(10, 17))


@dataclass(frozen=True)
class GeneratedScenario:
    generator_version: str
    generator_seed: int
    uncertainty_config_id: str
    scenario: ScenarioV3
    generation_attempt: int

    def manifest_entry(self, index: int | None = None) -> dict[str, Any]:
        encoded = json.dumps(
            self.scenario.to_dict(), sort_keys=True, separators=(",", ":")
        ).encode()
        entry: dict[str, Any] = {
            "generator_seed": self.generator_seed,
            "scenario_id": self.scenario.scenario_id,
            "scenario_root_seed": self.scenario.seed,
            "uncertainty_config_id": self.uncertainty_config_id,
            "zones": len(self.scenario.zones),
            "shelters": len(self.scenario.shelters),
            "horizon_steps": self.scenario.time.horizon_steps,
            "generation_attempt": self.generation_attempt,
            "scenario_sha256": hashlib.sha256(encoded).hexdigest(),
        }
        if index is not None:
            entry["index"] = index
        return entry


def _derived_seed(namespace: str, *values: int) -> int:
    payload = "|".join([namespace, *(str(value) for value in values)]).encode()
    return int.from_bytes(hashlib.sha256(payload).digest()[:8], "big") & (2**63 - 1)


def training_episode_generator_seed(
    training_seed: int, environment_rank: int, episode_index: int
) -> int:
    if training_seed < 0 or environment_rank < 0 or episode_index < 0:
        raise ValueError("training stream coordinates must be nonnegative")
    return _derived_seed(
        f"{TRAINING_GENERATOR_VERSION}-stream",
        training_seed,
        environment_rank,
        episode_index,
    )


def _location(node_id: str) -> dict[str, Any]:
    return {
        "kind": "ABSTRACT_NODE",
        "node_id": node_id,
        "latitude": None,
        "longitude": None,
    }


def _provenance(generator_version: str) -> dict[str, Any]:
    def component(classification: str, description: str) -> dict[str, Any]:
        return {
            "classification": classification,
            "description": description,
            "source_refs": [],
        }

    return {
        "scenario_origin": component(
            "SIMULATED", "Synthetic Phase 9 procedural training/validation scenario."
        ),
        "geography_origin": component(
            "FICTIONAL", "Randomized abstract nodes with no real coordinates."
        ),
        "population_origin": component("SIMULATED", "Randomized synthetic populations."),
        "shelter_origin": component("FICTIONAL", "Randomized synthetic shelters."),
        "hazard_origin": component("SIMULATED", "Randomized normalized hazard state."),
        "travel_origin": component("SIMULATED", "Randomized synthetic route timing."),
        "network_origin": component("FICTIONAL", "Randomized abstract route matrix."),
        "notes": [
            "SIMULATED / FICTIONAL PHASE 9 SCENARIO — NOT REAL DISASTER DATA.",
            f"Generated by {generator_version}; no policy or planner result enters generation.",
        ],
    }


def _opaque_ids(rng: random.Random, prefix: str, count: int) -> list[str]:
    # IDs control canonical slots, while the sampled values below describe physical
    # entities. Independent assignment breaks any fixed quality-to-slot relationship.
    tokens = rng.sample(range(100, 1_000), count)
    ids = [f"{prefix}{token:03d}" for token in tokens]
    rng.shuffle(ids)
    return ids


def _structure(generator_seed: int, uncertainty_override: str | None) -> tuple[int, int, int, str]:
    rng = random.Random(_derived_seed("phase9-structure-v1", generator_seed))
    zones = rng.choice(ZONE_COUNTS)
    shelters = rng.choice(SHELTER_COUNTS)
    horizon = rng.choice(HORIZONS)
    uncertainty = uncertainty_override or rng.choice(UNCERTAINTY_IDS)
    if uncertainty not in UNCERTAINTY_IDS:
        raise ValueError(f"unknown Phase 9 uncertainty configuration {uncertainty!r}")
    return zones, shelters, horizon, uncertainty


def _candidate(
    generator_seed: int,
    generator_version: str,
    attempt: int,
    uncertainty_override: str | None,
) -> tuple[dict[str, Any], str]:
    n_zones, n_shelters, horizon, uncertainty = _structure(
        generator_seed, uncertainty_override
    )
    rng = random.Random(_derived_seed("phase9-candidate-v1", generator_seed, attempt))
    zone_ids = _opaque_ids(rng, "Z", n_zones)
    shelter_ids = _opaque_ids(rng, "S", n_shelters)

    zones = []
    for physical_index, zone_id in enumerate(zone_ids):
        population = rng.randint(40, 110)
        zones.append(
            {
                "zone_id": zone_id,
                "location": _location(f"P9-ZONE-{physical_index:02d}"),
                "population_total": population,
                "population_initial_remaining": population,
                "vulnerable_population": int(population * rng.uniform(0.08, 0.38)),
                "medical_priority_population": int(population * rng.uniform(0.03, 0.22)),
                "initial_flood_severity": round(rng.uniform(0.12, 0.90), 6),
                "initial_severity_trend": rng.choice(["RISING", "STEADY", "FALLING"]),
                "priority_features": [],
            }
        )

    shelters = []
    for physical_index, shelter_id in enumerate(shelter_ids):
        capacity = rng.randint(100, 280)
        draw = rng.random()
        status = "OPEN" if draw < 0.76 else "RESTRICTED" if draw < 0.95 else "CLOSED"
        severity = rng.uniform(0.04, 0.78)
        if physical_index < 2:
            # Every accepted scenario has multiple initially usable destinations. Their
            # opaque IDs are independently randomized, so this creates no slot shortcut.
            status = "OPEN"
            severity = rng.uniform(0.04, 0.55)
        shelters.append(
            {
                "shelter_id": shelter_id,
                "location": _location(f"P9-SHELTER-{physical_index:02d}"),
                "capacity_total": capacity,
                "occupancy_initial": int(capacity * rng.uniform(0.0, 0.42)),
                "status": status,
                "status_reason": None if status == "OPEN" else "Synthetic Phase 9 status.",
                "initial_flood_severity": round(severity, 6),
                "accessibility_score": round(rng.uniform(0.30, 1.00), 6),
            }
        )

    routes = []
    for zone_index, zone in enumerate(zones):
        for shelter_index, shelter in enumerate(shelters):
            reachable = rng.random() < 0.82
            if shelter_index < 2:
                reachable = True
            mean = rng.uniform(5.0, 55.0) if reachable else None
            routes.append(
                {
                    "route_id": f"R-{zone['zone_id']}-{shelter['shelter_id']}",
                    "source_zone_id": zone["zone_id"],
                    "destination_shelter_id": shelter["shelter_id"],
                    "reachable": reachable,
                    "travel_time_mean": round(mean, 6) if mean is not None else None,
                    "travel_time_std": (
                        round(mean * rng.uniform(0.05, 0.28), 6)
                        if mean is not None
                        else None
                    ),
                    "base_closure_probability": (
                        round(rng.uniform(0.005, 0.15), 6) if reachable else None
                    ),
                }
            )

    raw = {
        "schema_version": "3.0",
        "scenario_id": f"{generator_version}-{generator_seed:016x}",
        "seed": _derived_seed("phase9-environment-root-v1", generator_seed, attempt),
        "provenance": _provenance(generator_version),
        "time": {"timestep_minutes": 10.0, "horizon_steps": horizon},
        "zones": zones,
        "shelters": shelters,
        "fleet": {
            "evacuation_enabled": True,
            "vehicle_count": rng.randint(3, 6),
            "vehicle_capacity": rng.randint(20, 50),
            "dispatches_per_timestep": 1,
        },
        "network": {
            "network_id": generator_version,
            "mode": "ABSTRACT_ROUTES",
            "routes": routes,
        },
        "hazard": {
            "severity_min": 0.0,
            "severity_max": 1.0,
            "scale_description": "Synthetic normalized Phase 9 severity scale.",
            "thresholds_are_modeling_assumptions": True,
        },
        "stochastic_model": {
            "parameter_status": "DEFERRED_TO_PHASE_4",
            "regional_shock_std": None,
            "local_noise_std": None,
            "shock_persistence": None,
            "travel_noise_std": None,
            "closure_hazard_coefficient": None,
            "shelter_degradation_probability": None,
        },
        "policy_context": {
            "constraint_cache_version": None,
            "policy_schema_version": "v3-ppo-training-spec-v1",
            "document_corpus_fingerprint": None,
        },
    }
    return raw, uncertainty


def generate_ppo_scenario(
    generator_seed: int,
    *,
    generator_version: str = TRAINING_GENERATOR_VERSION,
    uncertainty_config_id: str | None = None,
) -> GeneratedScenario:
    if isinstance(generator_seed, bool) or not isinstance(generator_seed, int) or generator_seed < 0:
        raise ValueError("generator_seed must be a nonnegative integer")
    if generator_version not in {TRAINING_GENERATOR_VERSION, VALIDATION_GENERATOR_VERSION}:
        raise ValueError("generator version is not frozen for Phase 9")
    for attempt in range(100):
        raw, uncertainty = _candidate(
            generator_seed, generator_version, attempt, uncertainty_config_id
        )
        scenario = ScenarioV3.from_dict(raw)
        snapshot = evaluate_actions(scenario, initialize_episode(scenario))
        allowed_dispatches = sum(
            action.to_dict()["action_type"] == "DISPATCH" and allowed
            for action, allowed in zip(snapshot.canonical_actions, snapshot.allowed_mask)
        )
        if allowed_dispatches >= len(scenario.zones):
            return GeneratedScenario(
                generator_version,
                generator_seed,
                uncertainty,
                scenario,
                attempt,
            )
    raise RuntimeError(f"could not generate accepted Phase 9 scenario {generator_seed}")


def permute_scenario_ids(
    scenario: ScenarioV3, permutation_seed: int
) -> tuple[ScenarioV3, dict[str, dict[str, str]]]:
    """Move physical entities among canonical slots while preserving their features."""
    rng = random.Random(_derived_seed("phase9-semantic-id-permutation-v1", permutation_seed))
    raw = scenario.to_dict()
    old_zone_ids = [item["zone_id"] for item in raw["zones"]]
    old_shelter_ids = [item["shelter_id"] for item in raw["shelters"]]
    new_zone_ids = old_zone_ids.copy()
    new_shelter_ids = old_shelter_ids.copy()
    while new_zone_ids == old_zone_ids:
        rng.shuffle(new_zone_ids)
    while new_shelter_ids == old_shelter_ids:
        rng.shuffle(new_shelter_ids)
    zone_map = dict(zip(old_zone_ids, new_zone_ids))
    shelter_map = dict(zip(old_shelter_ids, new_shelter_ids))
    for zone in raw["zones"]:
        zone["zone_id"] = zone_map[zone["zone_id"]]
    for shelter in raw["shelters"]:
        shelter["shelter_id"] = shelter_map[shelter["shelter_id"]]
    for index, route in enumerate(raw["network"]["routes"]):
        route["source_zone_id"] = zone_map[route["source_zone_id"]]
        route["destination_shelter_id"] = shelter_map[route["destination_shelter_id"]]
        route["route_id"] = f"PR{index:03d}-{route['source_zone_id']}-{route['destination_shelter_id']}"
    raw["scenario_id"] = f"{scenario.scenario_id}-perm-{permutation_seed}"
    raw["network"]["network_id"] = f"{raw['network']['network_id']}-permuted"
    raw["provenance"]["notes"].append(
        "Only semantic entity IDs and consistently dependent route IDs were permuted."
    )
    return ScenarioV3.from_dict(raw), {"zones": zone_map, "shelters": shelter_map}
