ZONE_COUNTS = (4, 5, 6)
SHELTER_COUNTS = (6, 7, 8, 9)
HORIZONS = tuple(range(10, 17))


def derived_seed(namespace: str, *values: int) -> int:
    payload = "|".join([namespace, *(str(value) for value in values)]).encode()
    return int.from_bytes(hashlib.sha256(payload).digest()[:8], "big") & (2**63 - 1)


def _location(node_id: str) -> dict[str, Any]:
    return {"kind": "ABSTRACT_NODE", "node_id": node_id, "latitude": None, "longitude": None}


def _provenance(version: str, suite: str) -> dict[str, Any]:
    def item(classification: str, description: str) -> dict[str, Any]:
        return {"classification": classification, "description": description, "source_refs": []}

    return {
        "scenario_origin": item("SIMULATED", f"Synthetic Phase 10 {suite} scenario."),
        "geography_origin": item("FICTIONAL", "Random abstract nodes; no real geography."),
        "population_origin": item("SIMULATED", "Random synthetic populations."),
        "shelter_origin": item("FICTIONAL", "Random synthetic shelter properties."),
        "hazard_origin": item("SIMULATED", "Random normalized synthetic hazards."),
        "travel_origin": item("SIMULATED", "Random synthetic route timing."),
        "network_origin": item("FICTIONAL", "Random abstract route matrix."),
        "notes": [
            "SIMULATED / FICTIONAL PHASE 10 SCENARIO — NOT REAL DISASTER DATA.",
            f"Generated by {version}; no policy result enters generation.",
        ],
    }


def _opaque_ids(rng: random.Random, prefix: str, count: int) -> list[str]:
    ids = [f"{prefix}{value:03d}" for value in rng.sample(range(100, 1_000), count)]
    rng.shuffle(ids)
    return ids


@dataclass(frozen=True)
class GeneratedEvaluationScenario:
    generator_version: str
    generator_seed: int
    uncertainty_config_id: str
    scenario: ScenarioV3
    generation_attempt: int
    suite: str
    stress_type: str | None = None

    def manifest_entry(self, index: int) -> dict[str, Any]:
        encoded = json.dumps(self.scenario.to_dict(), sort_keys=True, separators=(",", ":")).encode()
        return {
            "index": index,
            "suite": self.suite,
            "stress_type": self.stress_type,
            "generator_seed": self.generator_seed,
            "scenario_id": self.scenario.scenario_id,
            "scenario_root_seed": self.scenario.seed,
            "uncertainty_config_id": self.uncertainty_config_id,
            "zones": len(self.scenario.zones),
            "shelters": len(self.scenario.shelters),
            "horizon_steps": self.scenario.time.horizon_steps,
            "generation_attempt": self.generation_attempt,
            "replication_id": 0,
            "scenario_sha256": hashlib.sha256(encoded).hexdigest(),
        }


def _candidate(
    generator_seed: int,
    version: str,
    suite: str,
    attempt: int,
    uncertainty: str,
    stress_type: str | None,
) -> dict[str, Any]:
    structure_rng = random.Random(derived_seed(f"{version}-structure", generator_seed))
    n_zones = structure_rng.choice(ZONE_COUNTS)
    n_shelters = structure_rng.choice(SHELTER_COUNTS)
    horizon = structure_rng.choice(HORIZONS)
    rng = random.Random(derived_seed(f"{version}-candidate", generator_seed, attempt))
    zone_ids = _opaque_ids(rng, "Z", n_zones)
    shelter_ids = _opaque_ids(rng, "S", n_shelters)

    zones = []
    for physical_index, zone_id in enumerate(zone_ids):
        population = rng.randint(40, 110)
        if stress_type == "demand_shift":
            population = round(population * (rng.uniform(1.65, 2.20) if physical_index == 0 else rng.uniform(0.85, 1.05)))
        zones.append(
            {
                "zone_id": zone_id,
                "location": _location(f"P10-{suite}-ZONE-{physical_index:02d}"),
                "population_total": population,
                "population_initial_remaining": population,
                "vulnerable_population": int(population * rng.uniform(0.08, 0.38)),
                "medical_priority_population": int(population * rng.uniform(0.03, 0.22)),
                "initial_flood_severity": round(rng.uniform(0.12, 0.90), 6),
                "initial_severity_trend": rng.choice(["RISING", "STEADY", "FALLING"]),
                "priority_features": [],
            }
        )

    shelters = []
    for physical_index, shelter_id in enumerate(shelter_ids):
        capacity = rng.randint(100, 280)
        draw = rng.random()
        status = "OPEN" if draw < 0.76 else "RESTRICTED" if draw < 0.95 else "CLOSED"
        severity = rng.uniform(0.04, 0.78)
        if physical_index < 2:
            status = "OPEN"
            severity = rng.uniform(0.04, 0.55)
        shelters.append(
            {
                "shelter_id": shelter_id,
                "location": _location(f"P10-{suite}-SHELTER-{physical_index:02d}"),
                "capacity_total": capacity,
                "occupancy_initial": int(capacity * rng.uniform(0.0, 0.42)),
                "status": status,
                "status_reason": None if status == "OPEN" else "Synthetic Phase 10 status.",
                "initial_flood_severity": round(severity, 6),
                "accessibility_score": round(rng.uniform(0.30, 1.00), 6),
            }
        )

    routes = []
    for zone in zones:
        for shelter_index, shelter in enumerate(shelters):
            reachable = rng.random() < 0.82 or shelter_index < 2
            mean = rng.uniform(5.0, 55.0) if reachable else None
            if mean is not None and stress_type == "longer_travel_lags":
                mean *= 1.75
            routes.append(
                {
                    "route_id": f"R-{zone['zone_id']}-{shelter['shelter_id']}",
                    "source_zone_id": zone["zone_id"],
                    "destination_shelter_id": shelter["shelter_id"],
                    "reachable": reachable,
                    "travel_time_mean": round(mean, 6) if mean is not None else None,
                    "travel_time_std": round(mean * rng.uniform(0.05, 0.28), 6) if mean is not None else None,
                    "base_closure_probability": round(rng.uniform(0.005, 0.15), 6) if reachable else None,
                }
            )

    return {
        "schema_version": "3.0",
        "scenario_id": f"{version}-{generator_seed:016x}",
        "seed": derived_seed(f"{version}-environment-root", generator_seed, attempt),
        "provenance": _provenance(version, suite),
        "time": {"timestep_minutes": 10.0, "horizon_steps": horizon},
        "zones": zones,
        "shelters": shelters,
        "fleet": {
            "evacuation_enabled": True,
            "vehicle_count": rng.randint(3, 6),
            "vehicle_capacity": rng.randint(20, 50),
            "dispatches_per_timestep": 1,
        },
        "network": {"network_id": version, "mode": "ABSTRACT_ROUTES", "routes": routes},
        "hazard": {
            "severity_min": 0.0,
            "severity_max": 1.0,
            "scale_description": "Synthetic normalized Phase 10 severity scale.",
            "thresholds_are_modeling_assumptions": True,
        },
        "stochastic_model": {
            "parameter_status": "DEFERRED_TO_PHASE_4",
            "regional_shock_std": None,
            "local_noise_std": None,
            "shock_persistence": None,
            "travel_noise_std": None,
            "closure_hazard_coefficient": None,
            "shelter_degradation_probability": None,
        },
        "policy_context": {
            "constraint_cache_version": None,
            "policy_schema_version": "v3-phase10-eval-spec-v1",
            "document_corpus_fingerprint": None,
        },
    }


def generate_evaluation_scenario(
    generator_seed: int,
    *,
    suite: str,
    uncertainty_config_id: str,
    stress_type: str | None = None,
) -> GeneratedEvaluationScenario:
    if uncertainty_config_id not in UNCERTAINTY_IDS:
        raise ValueError("unknown uncertainty configuration")
    if suite not in {"heldout", "permutation_base", "stress"}:
        raise ValueError("unknown Phase 10 suite")
    if suite == "stress" and stress_type not in STRESS_TYPES:
        raise ValueError("stress scenarios require a frozen stress type")
    if suite != "stress" and stress_type is not None:
        raise ValueError("stress type is only valid for the stress suite")
    version = STRESS_GENERATOR_VERSION if suite == "stress" else HELDOUT_GENERATOR_VERSION
    for attempt in range(100):
        scenario = ScenarioV3.from_dict(
            _candidate(generator_seed, version, suite, attempt, uncertainty_config_id, stress_type)
        )
        snapshot = evaluate_actions(scenario, initialize_episode(scenario))
        allowed = sum(
            action.to_dict()["action_type"] == "DISPATCH" and permitted
            for action, permitted in zip(snapshot.canonical_actions, snapshot.allowed_mask)
        )
        if allowed >= len(scenario.zones):
            return GeneratedEvaluationScenario(
                version, generator_seed, uncertainty_config_id, scenario, attempt, suite, stress_type
            )
    raise RuntimeError(f"could not generate accepted Phase 10 scenario {generator_seed}")


def heldout_manifest() -> dict[str, Any]:
    entries = [
        generate_evaluation_scenario(
            seed, suite="heldout", uncertainty_config_id=UNCERTAINTY_IDS[index % 3]
        ).manifest_entry(index)
        for index, seed in enumerate(HELDOUT_SEEDS)
    ]
    return {
        "generator_version": HELDOUT_GENERATOR_VERSION,
        "number_of_scenarios": len(entries),
        "replication_id": 0,
        "uncertainty_counts": {"LOW": 200, "MEDIUM": 200, "HIGH": 200},
        "structural_range": {"zones": [4, 6], "shelters": [6, 9], "horizon_steps": [10, 16]},
        "entries": entries,
    }


def permutation_manifest() -> dict[str, Any]:
    bases = [
        generate_evaluation_scenario(
            seed, suite="permutation_base", uncertainty_config_id=UNCERTAINTY_IDS[index % 3]
        ).manifest_entry(index)
        for index, seed in enumerate(PERMUTATION_BASE_SEEDS)
    ]
    return {
        "diagnostic_version": PERMUTATION_VERSION,
        "generator_version": HELDOUT_GENERATOR_VERSION,
        "base_scenarios": bases,
        "permutations_per_base": 5,
        "paired_variants": 500,
        "permutation_seeds": {
            str(index): list(PERMUTATION_SEEDS[index * 5 : index * 5 + 5])
            for index in range(len(bases))
        },
        "alarm": {
            "median_absolute_normalised_return_difference": 0.05,
            "mean_absolute_safe_population_difference": 0.05,
            "label": "POTENTIAL_SLOT_SHORTCUT",
        },
    }


def stress_manifest() -> dict[str, Any]:
    entries = []
    for index, seed in enumerate(STRESS_SEEDS):
        category_index = index // 50
        stress_type = STRESS_TYPES[category_index]
        generated = generate_evaluation_scenario(
            seed,
            suite="stress",
            uncertainty_config_id=UNCERTAINTY_IDS[(index % 50) % 3],
            stress_type=stress_type,
        )
        entries.append(generated.manifest_entry(index))
    return {
        "generator_version": STRESS_GENERATOR_VERSION,
        "number_of_scenarios": len(entries),
        "scenarios_per_type": 50,
        "replication_id": 0,
        "interventions": {
            "sudden_flood_surge": "at t=3 add 0.18 zone and 0.10 shelter severity, clipped at 1",
            "route_closure_cascade": "at t=3 close deterministic SHA-ranked first ceiling(35%) of initially reachable routes",
            "shelter_failure": "at t=3 close the initially highest-capacity shelter; canonical ID breaks ties",
            "demand_shift": "at generation multiply physical zone 0 population by U[1.65,2.20] and others by U[0.85,1.05]",
            "longer_travel_lags": "at generation multiply every reachable route mean and derived standard deviation by 1.75",
        },
        "entries": entries,
    }


def permute_heldout_scenario(scenario: ScenarioV3, permutation_seed: int):
    return permute_scenario_ids(scenario, permutation_seed)
